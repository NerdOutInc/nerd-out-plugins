import { mkdtemp, readFile, rm, writeFile } from "node:fs/promises";
import os from "node:os";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { build } from "esbuild";

const buildDirectory = path.dirname(fileURLToPath(import.meta.url));
const bridgeDirectory = path.resolve(buildDirectory, "..");
const repositoryRoot = path.resolve(buildDirectory, "../../../..");
const temporaryDirectory = await mkdtemp(path.join(os.tmpdir(), "recall-bridge-build-"));
const checkOnly = process.argv.includes("--check");
const mcpRemotePackage = JSON.parse(
  await readFile(path.join(buildDirectory, "vendor/mcp-remote/package.json"), "utf8")
);

const banner = [
  `// Bundled from tracked ${mcpRemotePackage.name}@${mcpRemotePackage.version} source (${mcpRemotePackage.license} license — see LICENSE-mcp-remote.txt).`,
  "// Generated by bridge/build/build.mjs — do not edit by hand.",
  "import { createRequire } from 'node:module'; const require = createRequire(import.meta.url);",
].join("\n");

try {
  await build({
    absWorkingDir: buildDirectory,
    banner: { js: banner },
    bundle: true,
    entryNames: "[name]",
    entryPoints: {
      "mcp-remote-proxy.bundle": "vendor/mcp-remote/src/proxy.ts",
      "oauth-coordinator.bundle": "src/oauth-coordinator.ts",
    },
    format: "esm",
    legalComments: "none",
    minify: true,
    outdir: temporaryDirectory,
    outExtension: { ".js": ".mjs" },
    platform: "node",
    target: "node18",
  });

  const coordinatorManifest = `${JSON.stringify(
    {
      authorizationContractVersion: 1,
      entrypoint: "./oauth-coordinator.bundle.mjs",
      mcpRemoteVersion: mcpRemotePackage.version,
      modes: ["inspect", "authorize", "verify-only"],
      supportedClients: ["Claude", "Codex"],
    },
    null,
    2
  )}\n`;
  await writeFile(
    path.join(temporaryDirectory, "oauth-coordinator.json"),
    coordinatorManifest,
    "utf8"
  );

  const generatedFiles = [
    {
      source: path.join(temporaryDirectory, "mcp-remote-proxy.bundle.mjs"),
      targets: [
        path.join(bridgeDirectory, "mcp-remote-proxy.bundle.mjs"),
        path.join(repositoryRoot, "desktop-extensions/recall/server/mcp-remote-proxy.bundle.mjs"),
      ],
    },
    {
      source: path.join(temporaryDirectory, "oauth-coordinator.bundle.mjs"),
      targets: [path.join(bridgeDirectory, "oauth-coordinator.bundle.mjs")],
    },
    {
      source: path.join(temporaryDirectory, "oauth-coordinator.json"),
      targets: [path.join(bridgeDirectory, "oauth-coordinator.json")],
    },
  ];

  const staleTargets = [];
  for (const generatedFile of generatedFiles) {
    const rawGenerated = await readFile(generatedFile.source);
    const generated = generatedFile.source.endsWith(".mjs")
      ? Buffer.from(rawGenerated.toString("utf8").replace(/[\t ]+$/gm, ""), "utf8")
      : rawGenerated;
    for (const target of generatedFile.targets) {
      if (checkOnly) {
        const committed = await readFile(target).catch(() => null);
        if (!committed?.equals(generated)) staleTargets.push(target);
      } else {
        await writeFile(target, generated);
      }
    }
  }

  if (staleTargets.length > 0) {
    throw new Error(
      `Generated OAuth runtime artifacts are stale:\n${staleTargets
        .map((target) => `- ${path.relative(repositoryRoot, target)}`)
        .join("\n")}\nRun npm run build in plugins/recall/bridge/build.`
    );
  }

  console.log(
    `${checkOnly ? "Verified" : "Bundled"} tracked ${mcpRemotePackage.name}@${mcpRemotePackage.version} source and Recall OAuth coordinator.`
  );
} finally {
  await rm(temporaryDirectory, { force: true, recursive: true });
}
