// Bundles mcp-remote's proxy entry point into a single committed ESM file so
// the plugin's stdio bridge needs no npx, no network, and no node_modules at
// runtime. Run `npm install && npm run build` in this directory, then commit
// the regenerated ../mcp-remote-proxy.bundle.mjs.

import { readFileSync } from "node:fs";
import { createRequire } from "node:module";
import { build } from "esbuild";

const require = createRequire(import.meta.url);
const pkg = JSON.parse(
  readFileSync(require.resolve("mcp-remote/package.json"), "utf8")
);

await build({
  entryPoints: [require.resolve("mcp-remote/dist/proxy.js")],
  bundle: true,
  platform: "node",
  format: "esm",
  target: "node18",
  minify: true,
  legalComments: "none",
  outfile: "../mcp-remote-proxy.bundle.mjs",
  banner: {
    js: [
      `// Bundled from ${pkg.name}@${pkg.version} (${pkg.license} license — see LICENSE-mcp-remote.txt).`,
      "// Generated by bridge/build/build.mjs — do not edit by hand.",
      "import { createRequire } from 'node:module'; const require = createRequire(import.meta.url);",
    ].join("\n"),
  },
});

console.log(`Bundled ${pkg.name}@${pkg.version} -> ../mcp-remote-proxy.bundle.mjs`);
